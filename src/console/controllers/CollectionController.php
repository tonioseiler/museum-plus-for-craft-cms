    public function actionRemoveAttachments()
    {
        $itemIds = MuseumPlusItem::find()->ids();
        foreach($itemIds as $itemId) {
            $item = MuseumPlusItem::find()
                ->id($itemId)
                ->one();
            if($item->assetId) {
                $asset = Asset::find()->id($item->assetId)->one();
