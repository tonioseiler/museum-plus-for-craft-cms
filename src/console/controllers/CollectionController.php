    /**
     * @var bool|null if true - script will download all data.
     */
    public $forceAll;

    /**
     * @var string|null update-items with --forceAll: force only items not updated since this date
     * (e.g. "2026-11-16 00:00"), so a forced re-import in batches (--limit) takes the next items each run
     */
    public $updatedBefore;

    /**
     * @var int|null if set, script will downoad only this item.
     */
    public $collectionItemId;

    /**
     * @var bool|null if true - script will not download attachments.
     */
    public $ignoreAttachments;

    /**
     * @var bool|null if true - script will not download multimedia.
     */
    public $ignoreMultimedia;

    /**
     * @var bool|null if true - script will not download literature.
     */
    public $ignoreLiterature;

    /**
     * @var int startId - skip all items with id before this
     */
    public $startId;
    public $personId;

    /**
     * @var int|null update-items: queue at most this many create/update jobs; the others stay pending for the next run
     */
    public $limit;

    /**
     * @var bool|null update-items: one line per object with the reason (new, changed with both dates, up to date,
     * pending because of --limit); without it only the queued objects and the summary are printed
     */
    public $details;

    /**
     * @var bool|null update-items: the queued jobs print and log which fields of each object changed
     * (shown by queue/run --verbose and in the museumplus log)
     */
    public $fullDetails;

    /**
     * @var bool|null delete-removed-items: delete even if more than MAX_DELETE_SHARE of the items would be deleted
     */
    public $forceDelete;

    // delete-removed-items refuses to delete more than this share of the items (at least MAX_DELETE_MIN) without --forceDelete
    const MAX_DELETE_SHARE = 0.05;
    const MAX_DELETE_MIN = 50;

